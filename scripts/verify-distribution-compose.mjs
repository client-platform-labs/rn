#!/usr/bin/env node
/**
 * Map E #110 — Docker Compose smoke for Distribution Service.
 *
 * Usage:
 *   node scripts/verify-distribution-compose.mjs
 *
 * Requires: docker, docker compose
 */
import { spawn, spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "..");
const composeDir = path.join(repoRoot, "deploy/distribution-service");
const composeFile = path.join(composeDir, "docker-compose.yml");
const envFile = path.join(composeDir, ".env.verify");
const composeProject = "distribution-verify";

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    ...opts,
  });
  return r;
}

function dockerOk() {
  const r = run("docker", ["info"]);
  return r.status === 0;
}

if (!dockerOk()) {
  console.log("SKIP verify-distribution-compose: docker not available");
  process.exit(0);
}

const token = "compose-verify-" + Date.now();
writeFileSync(
  envFile,
  `# generated by verify-distribution-compose.mjs\nRN_CP_TOKEN=${token}\nRN_CP_ROLE=admin\nRN_CP_REGISTRY=file\nDISTRIBUTION_PORT=14040\n`,
);

const composeArgs = [
  "compose",
  "-p",
  composeProject,
  "--env-file",
  envFile,
  "-f",
  composeFile,
];

const up = run("docker", [...composeArgs, "up", "-d", "--build"], {
  cwd: composeDir,
});

if (up.status !== 0) {
  console.error("compose up failed", up.stderr || up.stdout);
  process.exit(1);
}

await new Promise((r) => setTimeout(r, 12000));

const base = "http://127.0.0.1:14040";

async function check() {
  try {
    const health = await fetch(`${base}/health`);
    const hj = await health.json();
    if (!health.ok || !hj.ok) throw new Error("health fail " + JSON.stringify(hj));
    console.log("OK /health");

    const svc = await fetch(`${base}/v1/service`);
    const sj = await svc.json();
    if (sj.mode !== "cp-serve") throw new Error("expected cp-serve mode");
    console.log("OK /v1/service cp-serve");

    const reg = await fetch(`${base}/v1/registry`);
    if (!reg.ok) throw new Error("registry fail");
    console.log("OK /v1/registry");

    const put = await fetch(`${base}/v1/dependency-manifest`, {
      method: "PUT",
      headers: {
        authorization: `Bearer ${token}`,
        "content-type": "application/json",
      },
      body: JSON.stringify({ dependencies: [], version_labels: {} }),
    });
    if (!put.ok) throw new Error("put manifest fail");
    console.log("OK PUT /v1/dependency-manifest with Bearer");

    const html = await fetch(`${base}/`);
    if (!html.ok || !(await html.text()).includes('data-console="distribution-reference"')) {
      throw new Error("console html missing");
    }
    console.log("OK Reference Console /");

    console.log("verify-distribution-compose: PASS");
  } finally {
    run("docker", [...composeArgs, "down", "-v"], { cwd: composeDir });
  }
}

check().catch((err) => {
  run("docker", [...composeArgs, "down", "-v"], { cwd: composeDir });
  console.error(err);
  process.exit(1);
});
